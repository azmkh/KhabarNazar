"""Image authenticity interface: is the picture AI-generated or a real photo?

This is deliberately separate from OCR (see ocr.py): whether the pixels were
generated by an AI model says nothing about whether the news claim is true.
"""

from __future__ import annotations

import logging

from app.ai.image import ai_detector

logger = logging.getLogger(__name__)

# Keep manipulation_prediction values short: they are stored in a VARCHAR(50) column.
# ("Not Analyzed" alone marks rows saved before the image pipeline had two branches.)
NOT_ANALYZED = "Not Analyzed: model unavailable"


def _unavailable(reason: str) -> dict:
    return {
        "image_score": None,
        "manipulation_prediction": NOT_ANALYZED,
        "is_stub": True,
        "status": "model_unavailable",
        "summary": f"Image authenticity was not analyzed: {reason}",
        "attribution_map": None,
        "model_version": None,
    }


def analyze_image(image_path: str) -> dict:
    """Run the AI-generated vs real detector, or return a clearly marked unavailable result.

    image_score is the ensemble's probability that the image is AI-generated (1 - P(real)).
    """
    detector, reason = ai_detector.load_detector()
    if detector is None:
        return _unavailable(reason)
    try:
        from PIL import Image

        with Image.open(image_path) as img:
            result = detector.analyse(img)
    except Exception:
        logger.exception("AI-generated image detection failed")
        return _unavailable("the detector failed on this image. Check the backend log.")

    p_real = result["p_real"]
    label = ai_detector.label_for(p_real)
    return {
        "image_score": round(1 - p_real, 4),
        "manipulation_prediction": label,
        "is_stub": False,
        "status": "completed",
        "summary": (
            f"The image detector rates this picture {label.lower()} "
            f"({1 - p_real:.0%} chance it is AI-generated, judged from the centre of the image). "
            "This is about the picture itself, not whether any news claim is true or false."
        ),
        "attribution_map": result["attribution_map"],
        "members": {name: round(value, 4) for name, value in result["members"].items()},
        "model_version": ai_detector.MODEL_VERSION,
    }
